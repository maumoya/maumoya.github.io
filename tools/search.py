"""Search index: the headings and card text of every page, written into search.js.

Each entry is one heading (h1, h2 or h3) with the text of the card or section it heads. Texts are the
same English keys tools/i18n.py cuts, so the browser can match a visitor's words in English and in the
language picked (window.mmT). Nothing is fetched at run time.

  python3 tools/search.py        rewrite the index block in search.js
  python3 tools/search.py check  exit 1 if the index in search.js is stale (CI)
"""
import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import i18n  # noqa: E402

ROOT = i18n.ROOT
JS = ROOT / "search.js"
START, END = "// index:start", "// index:end"
CARD = {"area", "card", "offer"}
NOISE = {"cta", "links", "cta-row", "buy", "more", "contact"}  # buttons and links, not content
SKIP = {"script", "style", "svg", "noscript", "template", "source", "head", "video", "dl", "figure"}


def classes(el):
    return set((el.attrs.get("class") or "").split())


def text_keys(el, out, stop=None):
    """Element keys under el, skipping cards (when stop is set) and headings."""
    for k in el.kids:
        if not isinstance(k, i18n.El) or k.tag in SKIP or k.attrs.get("translate") == "no":
            continue
        if "sr-only" in classes(k) or classes(k) & NOISE or (k.tag == "a" and "area" not in classes(k)):
            continue
        if stop and (k.tag == "article" or classes(k) & CARD):
            continue
        if k.tag not in ("h1", "h2", "h3"):
            key = i18n.element_key(k)
            if key and key not in out:
                out.append(key)
        text_keys(k, out, stop)


def entries(page):
    t = i18n.Tree()
    t.feed(page.read_text())
    rel = page.parent.relative_to(ROOT).as_posix()
    path = "" if rel == "." else rel + "/"
    out = []

    def walk(el, section):
        for k in el.kids:
            if not isinstance(k, i18n.El) or k.tag in SKIP:
                continue
            sec = k.attrs.get("id") if k.tag == "section" else section
            if k.tag in ("h1", "h2", "h3") and "sr-only" not in classes(k) and sec:
                title = i18n.element_key(k)
                card, node = None, k.parent
                while node is not None and node.tag != "section":
                    if node.tag == "article" or classes(node) & CARD:
                        card = node
                        break
                    node = node.parent
                body = []
                if card is not None:
                    text_keys(card, body)
                else:  # a section heading: the section's own text, not its cards
                    sect = k.parent
                    while sect is not None and sect.tag != "section":
                        sect = sect.parent
                    text_keys(sect, body, stop=k.tag != "h3")
                if title:
                    out.append({"p": path, "a": sec, "t": title, "b": [b for b in body if b != title]})
            walk(k, sec)

    walk(t.root, None)
    return out


def index():
    return [e for page in i18n.pages() for e in entries(page)]


def block():
    rows = ",\n".join("    " + json.dumps(e, ensure_ascii=False) for e in index())
    return f"{START} (generated by tools/search.py, do not edit)\n  var INDEX = [\n{rows}\n  ];\n  {END}"


def main():
    src = JS.read_text()
    pat = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    new = pat.sub(lambda m: block(), src, count=1)
    if sys.argv[1:] == ["check"]:
        if new != src:
            print("search index is stale, run python3 tools/search.py")
            return 1
        print("search index current")
        return 0
    JS.write_text(new)
    print(f"search index: {len(index())} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
